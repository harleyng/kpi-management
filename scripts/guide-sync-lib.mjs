import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generate `AGENTS.md` (Codex) and `GEMINI.md` (Gemini) from `CLAUDE.md`.
 *
 * One source of truth for the project guide. They have to be generated rather than shared
 * verbatim because Claude Code has real subagents under `.claude/agents/` and slash skills,
 * while the other two tools do not — a few passages must be reworded into "read the persona
 * file and adopt it yourself".
 *
 * `npm run guides:check` blocks drift in CI.
 */

export const scriptDir = dirname(fileURLToPath(import.meta.url));
export const rootDir = resolve(scriptDir, "..");

const generatedNotice = (source) =>
  [
    `> Generated from \`${source}\` by \`node scripts/sync-guide-files.mjs\`.`,
    "> Do not edit this file directly — edit the source and run `npm run guides:sync`.",
    "",
  ].join("\n");

/** Replacements shared by every generated variant. */
const rename = (title) => [
  [/^# CLAUDE\.md$/m, `# ${title}`],
  [/guidance for Claude Code \(claude\.ai\/code\)/g, `guidance for ${title.replace(".md", "")}`],
];

/**
 * Claude Code runs the expert panel as real subagents under `.claude/agents/` and exposes
 * slash skills. Codex and Gemini have neither — point them at the portable persona
 * definitions in `.agents/` and the equivalent written procedure.
 *
 * ⚠️ The search strings must match CLAUDE.md EXACTLY (line breaks and indentation included).
 * A string that no longer matches makes `applyReplacements` throw, so a CLAUDE.md edit that
 * breaks one fails `guides:sync` / `guides:check` instead of silently shipping slash commands
 * to tools that have none.
 */
const portableReplacements = [
  [
    "Eight subagents under `.claude/agents/` act as a virtual expert panel.",
    "Eight expert roles defined under `.agents/skills/` — read the persona file and adopt that perspective yourself; there is no subagent mechanism.",
  ],
  [
    "New route or page? Use\n   **`/new-page`**. New entity? Use **`/add-entity`**.",
    "New route or page? Follow `.claude/skills/new-page/SKILL.md`. New entity? Follow\n   `.claude/skills/add-entity/SKILL.md` (written procedures — there are no slash commands).",
  ],
  [
    "Changing a flow means using the\n    **`/update-flow`** skill.",
    "Changing a flow means following\n    `.claude/skills/update-flow/SKILL.md` as a written procedure.",
  ],
  [
    "run **`/log-decision`** to add a terse entry AND update the\nmatching current-truth file.",
    "add a terse entry to `.agents/knowledge/decisions-log.md` AND update the\nmatching current-truth file.",
  ],
];

export const filePairs = [
  {
    source: "CLAUDE.md",
    target: "AGENTS.md",
    replacements: [...rename("AGENTS.md"), ...portableReplacements],
  },
  {
    source: "CLAUDE.md",
    target: "GEMINI.md",
    replacements: [...rename("GEMINI.md"), ...portableReplacements],
  },
];

function applyReplacements(content, replacements) {
  return replacements.reduce((next, [pattern, replacement]) => {
    if (typeof pattern === "string" && !next.includes(pattern)) {
      throw new Error(
        `guide-sync: CLAUDE.md no longer contains the passage\n  ${JSON.stringify(pattern)}\n` +
          "Update portableReplacements in scripts/guide-sync-lib.mjs to match the new wording.",
      );
    }
    return next.replace(pattern, replacement);
  }, content);
}

/** Strip the "this file generates AGENTS.md/GEMINI.md" note — it is only true in the source. */
function stripSourceNote(content) {
  return content.replace(
    /\n> The companion files `AGENTS\.md` and `GEMINI\.md` are generated by[^\n]*\n> After editing this file[^\n]*\n/,
    "\n",
  );
}

function withGeneratedNotice(content, source) {
  const [title, ...rest] = content.split("\n");
  return [title, "", generatedNotice(source).trimEnd(), ...rest].join("\n");
}

export function buildGuideContent(sourcePath, replacements, source) {
  const sourceContent = readFileSync(sourcePath, "utf8");
  return `${withGeneratedNotice(
    applyReplacements(stripSourceNote(sourceContent), replacements),
    source,
  )}\n`;
}

function safeRead(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

export function getGuidePairs() {
  return filePairs.map(({ source, target, replacements }) => {
    const sourcePath = resolve(rootDir, source);
    const targetPath = resolve(rootDir, target);
    const expectedContent = buildGuideContent(sourcePath, replacements, source);
    const actualContent = safeRead(targetPath);
    return {
      source,
      target,
      sourcePath,
      targetPath,
      expectedContent,
      actualContent,
      inSync: expectedContent === actualContent,
    };
  });
}

export function syncGuides() {
  for (const { source, target, targetPath, expectedContent } of getGuidePairs()) {
    writeFileSync(targetPath, expectedContent);
    console.log(`Synced ${target} from ${source}`);
  }
}
